// The 10 models jtt_dcmut..pmb (below the original 5's functions in
// this file) are stored as R (190-value upper-triangular
// exchangeability) + eq (20-value equilibrium frequencies) instead of
// a literal precomputed 400-entry Q the way get_wag()/get_jtt()/etc.
// do - see build_Q_from_R()'s own comment for why, and
// find_model_entry() for the table these are looked up through. This
// is also the extensibility point for adding model #16+ later: one
// table entry, not a new function pair plus two new switch cases.
namespace
{
Matrix build_Q_from_R(const std::array<double, 190> &R, const std::array<double, 20> &eq);

struct ModelRFreqEntry
{
    model_type type;
    const char *name;
    const std::array<double, 190> *R;
    const std::array<double, 20> *eq;
};
const ModelRFreqEntry *find_model_entry(model_type model);
} // namespace

/*!
 * Function that gets the rate matrix for the specified model
 * @param model The wanted model
 * @return The rate matrix for that model
 */
Matrix get_model_matrix(model_type model)
{
    Matrix m;
    switch (model)
    {
    case jtt:
        m = get_jtt();
        break;
    case day:
        m = get_day();
        break;
    case mvr:
        m = get_mvr();
        break;
    case wag:
        m = get_wag();
        break;
    case lg:
        m = get_lg();
        break;
    default:
        if (const ModelRFreqEntry *entry = find_model_entry(model))
        {
            m = build_Q_from_R(*entry->R, *entry->eq);
        }
        break;
    }
    return m;
}

/*!
 * Gets the equilibrium distribution for a specified model
 * @param model The wanted model
 * @return The equilibrium distribution
 */
DblVec get_model_vec(model_type model)
{
    DblVec vec;
    switch (model)
    {
    case jtt:
        vec = get_jtt_eq();
        break;
    case day:
        vec = get_day_eq();
        break;
    case mvr:
        vec = get_mvr_eq();
        break;
    case wag:
        vec = get_wag_eq();
        break;
    case lg:
        vec = get_lg_eq();
        break;
    default:
        if (const ModelRFreqEntry *entry = find_model_entry(model))
        {
            vec.assign(entry->eq->begin(), entry->eq->end());
        }
        break;
    }
    return vec;
}

/*!
 * The mean substitution rate Q implies at its own, as-published
 * scale - see the header comment for why this isn't assumed to be a
 * fixed constant across models.
 * @param Q The rate matrix
 * @param eq Q's equilibrium distribution
 * @return -sum(eq[i] * Q(i,i))
 */
double mean_substitution_rate(const Matrix &Q, const DblVec &eq)
{
    double rate = 0.0;
    for (std::size_t i = 0; i < eq.size(); i++)
    {
        rate -= eq[i] * Q(i, i);
    }
    return rate;
}

