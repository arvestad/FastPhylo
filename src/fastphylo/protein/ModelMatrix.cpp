/*!
 * Q(i,j) = R(i,j)*eq[j] for i!=j, Q(i,i) = -row_sum - the diagonal is
 * always computed, never a hand-typed literal (unlike get_wag()/
 * get_jtt()/etc. above, which store a full precomputed Q): a hand-typed
 * diagonal value can be silently wrong (see the JTT Q(0,0) 100x bug,
 * fixed 2026-08-11 - a decimal-point transcription error that broke the
 * rows-sum-to-zero invariant for 30-40% wrong distances until caught); a
 * computed one cannot. R is the upper-triangular exchangeability array
 * in the standard PAML/IQ-TREE2 pair order every published model uses.
 * @param R The exchangeability values
 * @param eq The equilibrium distribution
 * @return The rate matrix Q
 */
Matrix build_Q_from_R(const std::array<double, 190> &R, const std::array<double, 20> &eq)
{
    Matrix Q(20, 20);
    std::size_t k = 0;
    for (std::size_t i = 0; i < 20; i++)
    {
        for (std::size_t j = i + 1; j < 20; j++)
        {
            Q(i, j) = R[k] * eq[j];
            Q(j, i) = R[k] * eq[i];
            k++;
        }
    }
    for (std::size_t i = 0; i < 20; i++)
    {
        double row_sum = 0.0;
        for (std::size_t j = 0; j < 20; j++)
        {
            if (j != i)
            {
                row_sum += Q(i, j);
            }
        }
        Q(i, i) = -row_sum;
    }
    return Q;
}

/*!
 * Looks up a model_type in the R+eq table above - the extensibility
 * point for adding model #16+ later (one table entry, not a new
 * function pair plus two new switch cases in get_model_matrix()/
 * get_model_vec()). Returns nullptr for anything not in this table
 * (the original 5 models, or id/jc/jck/jcss, which aren't real
 * substitution models at all).
 * @param model The wanted model
 * @return A pointer to the model's table entry, or nullptr if not found
 */
const ModelRFreqEntry *find_model_entry(model_type model)
{
    static const ModelRFreqEntry table[] = {
        {jtt_dcmut, "JTT-DCMUT", &R_jtt_dcmut, &eq_jtt_dcmut},
        {vt, "VT", &R_vt, &eq_vt},
        {hivb, "HIVb", &R_hivb, &eq_hivb},
        {hivw, "HIVw", &R_hivw, &eq_hivw},
        {cprev, "cpREV", &R_cprev, &eq_cprev},
        {blosum62, "BLOSUM62", &R_blosum62, &eq_blosum62},
        {dcmut, "DCMUT", &R_dcmut, &eq_dcmut},
        {mtrev, "MtREV", &R_mtrev, &eq_mtrev},
        {rtrev, "RtREV", &R_rtrev, &eq_rtrev},
        {pmb, "PMB", &R_pmb, &eq_pmb},
    };
    for (const auto &entry : table)
    {
        if (entry.type == model)
        {
            return &entry;
        }
    }
    return nullptr;
}
